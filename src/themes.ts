export type ThemeVars = Record<(typeof themeVarNames)[number], string>;

function toKebab(s: string): string {
  return s.replace(/([A-Z])/g, "-$1").toLowerCase().replace(/^-/, "");
}

const toCssVars = (t: ThemeVars): React.CSSProperties =>
  Object.fromEntries(
    themeVarNames.map((key) => [`--${toKebab(key)}`, t[key]])
  ) as React.CSSProperties;

